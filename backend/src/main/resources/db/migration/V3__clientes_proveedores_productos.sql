-- ===== 1. CLIENTE =====
CREATE TABLE IF NOT EXISTS cliente (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    telefono VARCHAR(30),
    direccion VARCHAR(255),
    ruc VARCHAR(20),
    pedidos_anuales INT
);

ALTER TABLE cliente ADD COLUMN IF NOT EXISTS codigo VARCHAR(20);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS tipo_documento VARCHAR(20);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS dni VARCHAR(8);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS razon_social VARCHAR(255);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS nombre_comercial VARCHAR(255);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS nombres VARCHAR(150);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS apellidos VARCHAR(150);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS correo VARCHAR(150);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

UPDATE cliente 
SET tipo_documento = CASE WHEN ruc IS NOT NULL AND ruc <> '' THEN 'RUC' ELSE 'SIN_DOCUMENTO' END
WHERE tipo_documento IS NULL;

ALTER TABLE cliente DROP CONSTRAINT IF EXISTS ck_cliente_tipo_documento;
ALTER TABLE cliente ADD CONSTRAINT ck_cliente_tipo_documento CHECK (tipo_documento IN ('RUC', 'DNI', 'SIN_DOCUMENTO'));

CREATE UNIQUE INDEX IF NOT EXISTS uk_cliente_codigo ON cliente (codigo);
CREATE UNIQUE INDEX IF NOT EXISTS uk_cliente_ruc ON cliente (ruc);
CREATE UNIQUE INDEX IF NOT EXISTS uk_cliente_dni ON cliente (dni);


