-- ===== 3. PRODUCTO =====
CREATE TABLE IF NOT EXISTS producto (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    estado VARCHAR(30),
    precio FLOAT,
    stock INT
);

ALTER TABLE producto ADD COLUMN IF NOT EXISTS codigo VARCHAR(30);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS tipo VARCHAR(10) NOT NULL DEFAULT 'PRODUCTO';
ALTER TABLE producto ADD COLUMN IF NOT EXISTS descripcion VARCHAR(500);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS categoria VARCHAR(80);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS precio_venta NUMERIC(12,2);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS precio_compra NUMERIC(12,2);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS stock_minimo INT;
ALTER TABLE producto ADD COLUMN IF NOT EXISTS unidad_medida VARCHAR(20);

UPDATE producto 
SET precio_venta = CAST(precio AS NUMERIC(12,2)) 
WHERE precio IS NOT NULL AND precio_venta IS NULL;

