-- V1: esquema del diagrama actual de HCG Multiservicios (11 tablas).
-- IF NOT EXISTS: si la BD ya tiene estas tablas no se toca nada (ademas Flyway
-- la marca como version 1 via baseline-on-migrate y ni siquiera ejecuta este archivo).
-- Se conservan nombres y tipos del diagrama. Las correcciones (NUMERIC, columnas
-- nuevas, FK faltantes) van en migraciones posteriores, de forma aditiva.
-- La relacion CLIENTE -> DETALLE_PEDIDOS del diagrama se considera un error de dibujo y no se crea.

CREATE TABLE IF NOT EXISTS proveedores (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255),
    ruc         VARCHAR(20),
    telefono_1  VARCHAR(30),
    telefono_2  VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS cliente (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(255),
    telefono         VARCHAR(30),
    direccion        VARCHAR(255),
    ruc              VARCHAR(20),
    pedidos_anuales  INT
);

CREATE TABLE IF NOT EXISTS producto (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(255),
    estado  VARCHAR(30),
    precio  FLOAT,
    stock   INT
);

CREATE TABLE IF NOT EXISTS cotizacion (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   INT REFERENCES cliente (id),
    cliente      VARCHAR(255),
    fecha        DATE,
    presupuesto  FLOAT,
    telefono     VARCHAR(30),
    estado       VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS detalle_cotizacion (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion  INT REFERENCES cotizacion (id),
    id_producto    INT REFERENCES producto (id),
    producto       VARCHAR(255),
    cantidad       VARCHAR(30),
    unidades       VARCHAR(30),
    precio_unit    FLOAT,
    precio_total   FLOAT
);

CREATE TABLE IF NOT EXISTS guias (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente         INT REFERENCES cliente (id),
    fecha              DATE,
    direccion          VARCHAR(255),
    monto_total        FLOAT,
    telefono           VARCHAR(30),
    direccion_fiscal   VARCHAR(255),
    direccion_envio    VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS detalle_guias (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_guia       INT REFERENCES guias (id),
    id_producto   INT REFERENCES producto (id),
    producto      VARCHAR(255),
    cantidad      INT,
    unidades      VARCHAR(30),
    precio_unit   FLOAT,
    precio_total  FLOAT
);

CREATE TABLE IF NOT EXISTS pedidos_proveedor (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente       VARCHAR(255),
    fecha         DATE,
    id_proveedor  INT REFERENCES proveedores (id),
    proveedor     VARCHAR(255),
    monto         FLOAT,
    ruc           VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS detalle_pedidos (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido     INT REFERENCES pedidos_proveedor (id),
    producto      VARCHAR(255),
    cantidad      INT,
    unidades      VARCHAR(30),
    precio_unit   FLOAT,
    precio_total  FLOAT
);

CREATE TABLE IF NOT EXISTS compras_egresos (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor   INT REFERENCES proveedores (id),
    proveedor      VARCHAR(255),
    fecha          DATE,
    gasto          FLOAT,
    modalidad      VARCHAR(60),
    justificacion  TEXT
);

CREATE TABLE IF NOT EXISTS cuentas (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente    INT REFERENCES cliente (id),
    id_proveedor  INT REFERENCES proveedores (id),
    nombre        VARCHAR(255),
    banco         VARCHAR(100),
    categoria     VARCHAR(60),
    moneda        VARCHAR(10),
    cle_prov      VARCHAR(60)
);
