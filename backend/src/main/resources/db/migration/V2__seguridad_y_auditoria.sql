-- V2: usuarios, roles, permisos y auditoria. Solo agrega tablas; no toca las existentes.
-- username y correo se guardan en minusculas (lo garantiza el servicio) para que UNIQUE sea insensible a mayusculas.

CREATE TABLE permiso (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(60)  NOT NULL UNIQUE,
    modulo       VARCHAR(40)  NOT NULL,
    accion       VARCHAR(20)  NOT NULL,
    descripcion  VARCHAR(200)
);

CREATE TABLE rol (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(40)  NOT NULL UNIQUE,
    descripcion  VARCHAR(200),
    sistema      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE rol_permiso (
    rol_id      BIGINT NOT NULL REFERENCES rol (id) ON DELETE CASCADE,
    permiso_id  BIGINT NOT NULL REFERENCES permiso (id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           VARCHAR(50)  NOT NULL UNIQUE,
    nombre_completo    VARCHAR(150) NOT NULL,
    correo             VARCHAR(150) NOT NULL UNIQUE,
    password_hash      VARCHAR(100) NOT NULL,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos  INT          NOT NULL DEFAULT 0,
    bloqueado_hasta    TIMESTAMP,
    ultimo_login       TIMESTAMP,
    creado_en          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE usuario_rol (
    usuario_id  BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    rol_id      BIGINT NOT NULL REFERENCES rol (id),
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE auditoria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    username        VARCHAR(50),
    accion          VARCHAR(60)  NOT NULL,
    entidad         VARCHAR(60),
    entidad_id      VARCHAR(60),
    valor_anterior  VARCHAR(2000),
    valor_nuevo     VARCHAR(2000),
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_fecha ON auditoria (fecha);
CREATE INDEX idx_auditoria_entidad ON auditoria (entidad, entidad_id);

