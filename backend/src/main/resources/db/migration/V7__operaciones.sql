-- V7: operaciones (seguimiento comercial: ventas, compras y pedidos con su linea de tiempo).
-- Una operacion agrupa lo que ocurre con un cliente o proveedor (solicitud, cotizacion, envio, despacho, boleta...).

CREATE TABLE operacion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(20),
    tipo               VARCHAR(20)   NOT NULL,
    titulo             VARCHAR(255)  NOT NULL,
    descripcion        VARCHAR(500),
    cliente_id         INT REFERENCES cliente (id),
    proveedor_id       INT REFERENCES proveedores (id),
    contraparte_nombre VARCHAR(255)  NOT NULL,
    estado             VARCHAR(20)   NOT NULL DEFAULT 'ABIERTA',
    monto              NUMERIC(12,2) NOT NULL DEFAULT 0,
    fecha_inicio       DATE          NOT NULL,
    fecha_cierre       DATE,
    usuario_id         BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    creado_en          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_operacion_tipo CHECK (tipo IN ('VENTA', 'COMPRA', 'PEDIDO')),
    CONSTRAINT ck_operacion_estado CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA'))
);

CREATE UNIQUE INDEX uk_operacion_codigo ON operacion (codigo);
CREATE INDEX idx_operacion_estado ON operacion (estado);
CREATE INDEX idx_operacion_tipo ON operacion (tipo);
CREATE INDEX idx_operacion_cliente ON operacion (cliente_id);
CREATE INDEX idx_operacion_proveedor ON operacion (proveedor_id);

CREATE TABLE operacion_evento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id  BIGINT       NOT NULL REFERENCES operacion (id) ON DELETE CASCADE,
    tipo          VARCHAR(20)  NOT NULL,
    titulo        VARCHAR(150) NOT NULL,
    detalle       VARCHAR(500),
    referencia    VARCHAR(60),
    fecha         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id    BIGINT REFERENCES usuario (id) ON DELETE SET NULL
);

CREATE INDEX idx_operacion_evento_operacion ON operacion_evento (operacion_id);

-- Permisos del modulo (ADMIN siempre tiene todos; al resto los asigna el administrador).
INSERT INTO permiso (codigo, modulo, accion, descripcion)
SELECT 'OPERACIONES_' || a.accion, 'OPERACIONES', a.accion, a.accion || ' OPERACIONES'
FROM (VALUES ('VER'), ('CREAR'), ('EDITAR'), ('ANULAR')) AS a (accion);

INSERT INTO rol_permiso (rol_id, permiso_id)
SELECT r.id, p.id FROM rol r CROSS JOIN permiso p WHERE r.nombre = 'ADMIN' AND p.modulo = 'OPERACIONES';
