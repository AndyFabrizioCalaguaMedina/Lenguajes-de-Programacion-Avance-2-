-- 1. Crear tabla cotizacion si no existe (asegura ejecucion si V1 fue ignorada)
CREATE TABLE IF NOT EXISTS cotizacion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT REFERENCES cliente (id),
    cliente VARCHAR(255),
    fecha DATE,
    presupuesto FLOAT,
    telefono VARCHAR(30),
    estado VARCHAR(30)
);

