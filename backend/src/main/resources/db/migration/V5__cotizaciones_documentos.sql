ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS moneda VARCHAR(3) NOT NULL DEFAULT 'PEN';
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS subtotal NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS igv NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS total NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS vigencia_hasta DATE;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS observacion VARCHAR(500);
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS usuario_id BIGINT;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS comprobante_id BIGINT;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE UNIQUE INDEX IF NOT EXISTS uk_cotizacion_numero ON cotizacion (numero);

-- 3. Crear tabla detalle_cotizacion si no existe
CREATE TABLE IF NOT EXISTS detalle_cotizacion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion INT REFERENCES cotizacion (id),
    id_producto INT REFERENCES producto (id),
    producto VARCHAR(255),
    cantidad VARCHAR(30),
    unidades VARCHAR(30),
    precio_unit FLOAT,
    precio_total FLOAT
);

-- 4. Modificar/agregar columnas de detalle_cotizacion
ALTER TABLE detalle_cotizacion ADD COLUMN IF NOT EXISTS item INT;
ALTER TABLE detalle_cotizacion ADD COLUMN IF NOT EXISTS cantidad_num NUMERIC(12,2);
ALTER TABLE detalle_cotizacion ADD COLUMN IF NOT EXISTS precio_unitario NUMERIC(12,2);
ALTER TABLE detalle_cotizacion ADD COLUMN IF NOT EXISTS subtotal NUMERIC(12,2);

-- 5. Registro central de documentos
CREATE TABLE IF NOT EXISTS documento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               VARCHAR(30)   NOT NULL,
    numero             VARCHAR(40)   NOT NULL,
    fecha              DATE          NOT NULL,
    origen             VARCHAR(20)   NOT NULL,
    origen_id          VARCHAR(40),
    contraparte_nombre VARCHAR(255),
    contraparte_doc    VARCHAR(20),
    monto              NUMERIC(12,2) NOT NULL DEFAULT 0,
    moneda             VARCHAR(3)    NOT NULL DEFAULT 'PEN',
    estado             VARCHAR(20)   NOT NULL,
    descripcion        VARCHAR(500),
    archivo_url        VARCHAR(500),
    usuario_id         BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    creado_en          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_documento_tipo_numero UNIQUE (tipo, numero)
);

CREATE INDEX IF NOT EXISTS idx_documento_fecha ON documento (fecha);
CREATE INDEX IF NOT EXISTS idx_documento_tipo ON documento (tipo);