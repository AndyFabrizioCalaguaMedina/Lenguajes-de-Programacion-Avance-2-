-- V6: salidas de bodega (productos que salen del almacen: envios a proveedores, devoluciones, ventas, mermas).
-- Cada salida descuenta stock y guarda el stock anterior/posterior de cada producto (trazabilidad tipo kardex).

CREATE TABLE salida_bodega (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          VARCHAR(20),
    fecha           TIMESTAMP    NOT NULL,
    destino_tipo    VARCHAR(20)  NOT NULL,
    proveedor_id    INT REFERENCES proveedores (id),
    cliente_id      INT REFERENCES cliente (id),
    destino_nombre  VARCHAR(255),
    motivo          VARCHAR(20)  NOT NULL,
    observacion     VARCHAR(500),
    estado          VARCHAR(20)  NOT NULL DEFAULT 'REGISTRADA',
    usuario_id      BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    creado_en       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    anulado_en      TIMESTAMP
);

CREATE UNIQUE INDEX uk_salida_bodega_numero ON salida_bodega (numero);
CREATE INDEX idx_salida_bodega_fecha ON salida_bodega (fecha);
CREATE INDEX idx_salida_bodega_estado ON salida_bodega (estado);

CREATE TABLE salida_bodega_detalle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salida_id        BIGINT       NOT NULL REFERENCES salida_bodega (id) ON DELETE CASCADE,
    item             INT          NOT NULL,
    producto_id      INT          NOT NULL REFERENCES producto (id),
    codigo           VARCHAR(30),
    descripcion      VARCHAR(255),
    cantidad         INT          NOT NULL,
    stock_anterior   INT          NOT NULL,
    stock_posterior  INT          NOT NULL
);

CREATE INDEX idx_salida_detalle_salida ON salida_bodega_detalle (salida_id);
CREATE INDEX idx_salida_detalle_producto ON salida_bodega_detalle (producto_id);

-- Permisos del modulo (ADMIN siempre tiene todos; al resto los asigna el administrador).
INSERT INTO permiso (codigo, modulo, accion, descripcion)
SELECT 'BODEGA_' || a.accion, 'BODEGA', a.accion, a.accion || ' BODEGA'
FROM (VALUES ('VER'), ('CREAR'), ('EDITAR'), ('ANULAR')) AS a (accion);

INSERT INTO rol_permiso (rol_id, permiso_id)
SELECT r.id, p.id FROM rol r CROSS JOIN permiso p WHERE r.nombre = 'ADMIN' AND p.modulo = 'BODEGA';
