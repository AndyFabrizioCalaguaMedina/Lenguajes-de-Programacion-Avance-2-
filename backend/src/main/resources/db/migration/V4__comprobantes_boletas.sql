CREATE TABLE comprobante (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_doc            VARCHAR(2)    NOT NULL,
    serie               VARCHAR(4)    NOT NULL,
    correlativo         INT           NOT NULL,
    fecha_emision       TIMESTAMP     NOT NULL,
    moneda              VARCHAR(3)    NOT NULL DEFAULT 'PEN',
    cliente_id          INT REFERENCES cliente (id) ON DELETE SET NULL,
    cliente_tipo_doc    VARCHAR(2),
    cliente_num_doc     VARCHAR(20),
    cliente_nombre      VARCHAR(255),
    cliente_direccion   VARCHAR(255),
    mto_oper_gravadas   NUMERIC(12,2) NOT NULL,
    mto_igv             NUMERIC(12,2) NOT NULL,
    mto_imp_venta       NUMERIC(12,2) NOT NULL,
    observacion         VARCHAR(500),
    estado              VARCHAR(20)   NOT NULL,
    codigo_sunat        VARCHAR(60),
    descripcion_sunat   VARCHAR(1000),
    hash                VARCHAR(100),
    xml                 VARCHAR(1000000),
    cdr_zip             VARCHAR(1000000),
    request_json        VARCHAR(100000),
    usuario_id          BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    creado_en           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_comprobante_numero UNIQUE (tipo_doc, serie, correlativo)
);

CREATE INDEX idx_comprobante_estado ON comprobante (estado);
CREATE INDEX idx_comprobante_fecha ON comprobante (fecha_emision);
CREATE INDEX idx_comprobante_cliente ON comprobante (cliente_id);

CREATE TABLE comprobante_detalle (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprobante_id      BIGINT        NOT NULL REFERENCES comprobante (id) ON DELETE CASCADE,
    item                INT           NOT NULL,
    cod_producto        VARCHAR(30),
    descripcion         VARCHAR(500)  NOT NULL,
    unidad              VARCHAR(5),
    cantidad            NUMERIC(12,2) NOT NULL,
    valor_unitario      NUMERIC(12,2) NOT NULL,
    precio_unitario     NUMERIC(12,2) NOT NULL,
    valor_venta         NUMERIC(12,2) NOT NULL,
    igv                 NUMERIC(12,2) NOT NULL
);

CREATE INDEX idx_comprobante_detalle_comp ON comprobante_detalle (comprobante_id);
